from textwrap import dedent


SYSTEM_PROMPT = dedent(
    """
    너는 한국어 웹소설의 시놉시스를 읽고 작품 관리용 캐릭터 설정집을 만드는 분석가다.
    반드시 JSON만 반환한다.
    원문 근거가 부족한 값은 빈 문자열로 둔다.
    필드명은 지정된 JSON 형식을 절대 변경하지 않는다.
    """
).strip()


def build_character_extract_prompt(*, work_title: str, genre: str, synopsis: str, limit: int) -> str:
    return dedent(
        f"""
        [작품 정보]
        제목: {work_title or '작품'}
        장르: {genre or '장르 미입력'}

        [시놉시스]
        {synopsis}

        [반환 JSON 형식]
        {{
          "characters": [
            {{
              "char_name": "필수, 30자 이내",
              "age": "선택, 10자 이내",
              "role": "선택, 10자 이내",
              "profile_label": "선택, 80자 이내",
              "gender": "필수, M/F/U 중 하나",
              "relationships": "선택, 500자 이내",
              "appearance": "선택, 300자 이내",
              "detail_setting": "선택, 1000자 이내"
            }}
          ]
        }}

        [필드 작성 기준]
        - char_name: 캐릭터 이름. 반드시 있어야 한다.
        - age: 나이. 명확하지 않으면 빈 문자열로 둔다.
        - role: 작품 내 역할. 예: 주인공, 조력자, 악역, 라이벌, 동료, 스승, 기타
        - profile_label: 관계도 카드 하단에 표시할 짧은 라벨이다.
          원문에 명확히 드러난 직업, 신분, 작위, 공식 직책, 계급이 있으면 작성한다.
          관계나 작품 내 역할만으로 라벨을 만들지 말고, 명확한 근거가 없으면 빈 문자열로 둔다.
        - gender: 성별 코드. 반드시 M, F, U 중 하나로만 작성한다.
          M: 남성으로 판단되는 경우.
          F: 여성으로 판단되는 경우.
          U: 원문 근거가 부족하거나 판단 불가한 경우.
          왕자, 공주, 황태자, 공작가 영애, 기사단장 같은 직위·신분·작위·직책은 gender에 넣지 말고 profile_label에 넣는다.
        - relationships: 다른 주요 인물과의 관계를 요약한다.
        - appearance: 외형 정보를 요약한다.
        - detail_setting: 성격, 말투, 배경 서사, 목표, 갈등을 요약한다.
          원문에 명확히 드러난 직업, 신분, 작위, 공식 직책, 계급이 있다면 이 필드 안에 자연스럽게 포함한다.

        [세부 설정 안전 규칙]
        - 직업, 신분, 작위, 공식 직책, 계급은 시놉시스에서 명확히 확인되는 경우에만 작성한다.
        - 정보가 명확하지 않은 인물에게 직업, 신분, 작위, 소속 내 위치를 추측해서 붙이지 않는다.
        - 단순히 "주인공", "악역", "조력자", "친구", "연인", "가족" 같은 작품 내 역할만으로 사회적 위치를 만들어내지 않는다.
        - 명시된 사회적 위치가 없다면 detail_setting은 성격, 목적, 갈등, 관계 중심으로 작성한다.

        [규칙]
        - 최대 {limit}명까지만 추출한다.
        - 이름이 없는 항목은 만들지 않는다.
        - 작품 속 인물이 아닌 추상 개념은 캐릭터로 만들지 않는다.
        - 단역이나 엑스트라는 제외하고 주요 인물 위주로 추출한다.
        - 같은 인물의 본명, 별명, 호칭은 하나의 캐릭터로 병합한다.
        - 내용은 모두 한국어로 작성한다.
        - 과장해서 새 설정을 만들지 말고 시놉시스에서 확인 가능한 내용만 정리한다.
        - 원문에서 확인할 수 없는 값은 추측하지 말고 빈 문자열로 둔다.
        - 반드시 JSON만 반환하고, 설명 문장은 붙이지 않는다.
        """
    ).strip()
